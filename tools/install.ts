// Install the addon, Config.lua with its server namespace,
// and a pool of 200 LoD slots. Never overwrite directories lacking
// our installation marker.
//
//   bun tools/install.ts --addons "<WoW>\Interface\AddOns" [--server-namespace wow-forever]
import { cpSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { dataPaths, defaultDataDir } from '../bridge/src/config.js';
import { resourcePath } from '../bridge/src/paths.js';
import { EMPTY_INBOX, KIT_MARKER, POOL_MARKER, SLOT_COUNT, slotName, slotToc } from '../bridge/src/transport/delivery.js';
import { luaString } from '../bridge/src/transport/lua.js';

export const DEFAULT_SERVER_NAMESPACE = 'wow-forever';
const ADDON = 'ForeverAssistant';

export interface InstallOptions {
  addonsDir: string;
  serverNamespace: string;
  sourceDir?: string;
  slotCount?: number;
  transport?: 'pixels' | 'silent_voice';
}

export interface InstallReport {
  addonDir: string;
  slotsWritten: number;
  slotsForeign: string[];
}

export class InstallError extends Error {}

export function configLua(serverNamespace: string, slotCount: number, transport: 'pixels' | 'silent_voice' = 'pixels'): string {
  return [
    '-- Generated by tools/install.ts. Reinstalling overwrites this file.',
    'ForeverAssistantConfig = {',
    `  serverNamespace = ${luaString(serverNamespace)},`,
    `  slotCount = ${slotCount},`,
    `  transport = ${luaString(transport)},`,
    '}',
    '',
  ].join('\n');
}

export function installKit(options: InstallOptions): InstallReport {
  const { addonsDir, serverNamespace } = options;
  const slotCount = options.slotCount ?? SLOT_COUNT;
  if (!existsSync(addonsDir) || !statSync(addonsDir).isDirectory()) {
    throw new InstallError(`AddOns directory not found: ${addonsDir}`);
  }
  if (serverNamespace.length === 0 || Buffer.byteLength(serverNamespace) > 1024) {
    throw new InstallError('serverNamespace must be a non-empty string of at most 1024 bytes');
  }

  const addonDir = join(addonsDir, ADDON);
  const toc = join(addonDir, `${ADDON}.toc`);
  if (existsSync(addonDir) && !(existsSync(toc) && readFileSync(toc, 'utf8').includes(KIT_MARKER))) {
    throw new InstallError(`${addonDir} exists without our installation marker; refusing to overwrite it`);
  }
  cpSync(options.sourceDir ?? resourcePath('addon', ADDON), addonDir, { recursive: true });
  writeFileSync(join(addonDir, 'Config.lua'), configLua(serverNamespace, slotCount, options.transport), 'utf8');

  const slotsForeign: string[] = [];
  let slotsWritten = 0;
  for (let i = 1; i <= slotCount; i++) {
    const dir = join(addonsDir, slotName(i));
    const tocPath = join(dir, `${slotName(i)}.toc`);
    if (existsSync(dir) && !(existsSync(tocPath) && readFileSync(tocPath, 'utf8').includes(POOL_MARKER))) {
      slotsForeign.push(slotName(i));
      continue;
    }
    mkdirSync(dir, { recursive: true });
    writeFileSync(tocPath, slotToc(i), 'utf8');
    const inbox = join(dir, 'Inbox.lua');
    if (!existsSync(inbox)) writeFileSync(inbox, EMPTY_INBOX, 'utf8');
    slotsWritten++;
  }
  return { addonDir, slotsWritten, slotsForeign };
}

function argument(name: string): string | undefined {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function main(): number {
  const paths = dataPaths(defaultDataDir());
  const saved: Record<string, unknown> = existsSync(paths.config) ? JSON.parse(readFileSync(paths.config, 'utf8')) : {};
  const addonsDir = argument('--addons') ?? (typeof saved.addonsPath === 'string' ? saved.addonsPath : undefined);
  const serverNamespace =
    argument('--server-namespace') ??
    (typeof saved.serverNamespace === 'string' ? saved.serverNamespace : DEFAULT_SERVER_NAMESPACE);
  if (!addonsDir) {
    console.error('Specify the AddOns directory: --addons "<WoW>\\Interface\\AddOns"');
    return 2;
  }
  let report: InstallReport;
  try {
    report = installKit({ addonsDir, serverNamespace, transport: saved.transport === 'silent_voice' ? 'silent_voice' : 'pixels' });
  } catch (error) {
    console.error(error instanceof InstallError ? error.message : String(error));
    return 1;
  }
  mkdirSync(paths.dataDir, { recursive: true });
  writeFileSync(paths.config, `${JSON.stringify({ ...saved, addonsPath: addonsDir, serverNamespace }, null, 2)}\n`, 'utf8');
  console.log(`Addon: ${report.addonDir}`);
  console.log(`Slots written: ${report.slotsWritten}; server namespace: ${serverNamespace}`);
  console.log(`Bridge settings: ${paths.config}`);
  if (report.slotsForeign.length > 0) {
    console.error(`Skipped foreign directories without the pool marker: ${report.slotsForeign.join(', ')}`);
    return 1;
  }
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(main());
